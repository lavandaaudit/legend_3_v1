  IB.houseTalk=function(b,extra){
    extra=extra||[];
    const D=T[b.type];
    const ID=(IB.INT_DEFS&&IB.INT_DEFS[b.type])||{};
    const host=D?D.host:(ID.owner||'ГОСПОДАР');
    const title=D?D.title:(ID.title||'БУДИНОК');
    const bid=b.type+':'+((b.x|0))+','+((b.y|0));
    const talk=(IB.G.talk||(IB.G.talk={}));          /* v19: у сейві */
    const st=talk[bid]||(talk[bid]={n:0,a:0});
    st.n++;                                           /* візит */
    const greet=D&&D.greet?D.greet[(st.n+IB.G.day)%D.greet.length]
      :ID.greet||'«Ось ті легендарні, про яких радіо говорить. Питайте — відповім.»';
    const topics=D&&D.topics?D.topics:[];
    const thanks=()=>{for(const h of IB.E.team)h.mood=IB.clamp(h.mood+2,0,100);
      IB.toast('Тепла розмова: настрій +2','gold');IB.closeDlg&&IB.closeDlg();};
    const build=()=>{
      const items=[];
      const off=st.a%Math.max(1,topics.length);
      for(let i=0;i<topics.length;i++){
        const tp=topics[(off+i)%topics.length];
        items.push({t:'❓ '+tp.q,f:()=>ask(tp)});
      }
      for(const ex of extra)items.push(ex);
      items.push({t:'👏 Подякувати і піти',f:thanks});
      IB.openDialog(host+' — '+title,greet,items.slice(0,7));
    };
    const ask=(tp)=>{
      const al=tp.a;
      const vi=(st.a++)%al.length;                    /* варіант крутиться */
      let ans=al[vi];
      if(typeof ans==='object')ans=ans[IB.act?IB.act():1]||ans[1]||Object.values(ans)[0];
      IB.openDialog(host+' — РОЗМОВА',ans,[
        {t:'❓ Ще одне питання',f:build},
        {t:'👏 Дякуємо, до зустрічі',f:thanks}
      ]);
    };
    build();
  };
